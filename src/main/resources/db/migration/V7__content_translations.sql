-- Phase 7 (Step 28): database-backed content translations.
-- Replaces the single `categories.name_pt` override with symmetric EN/PT
-- translation rows for categories and products. Canonical name/description
-- columns remain as the fallback for legacy clients and unique constraints.
create table category_translations (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    category_id bigint not null,
    description varchar(500),
    locale varchar(8) not null,
    name varchar(100) not null,
    primary key (id)
);

alter table if exists category_translations
    add constraint uq_category_translation unique (category_id, locale);

alter table if exists category_translations
    add constraint fk_category_translation_category
    foreign key (category_id) references categories(id) on delete cascade;

create table product_translations (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    product_id bigint not null,
    description TEXT,
    locale varchar(8) not null,
    name varchar(100) not null,
    primary key (id)
);

alter table if exists product_translations
    add constraint uq_product_translation unique (product_id, locale);

alter table if exists product_translations
    add constraint fk_product_translation_product
    foreign key (product_id) references products(id) on delete cascade;

-- English is the canonical language: copy the existing columns.
insert into category_translations (created_at, updated_at, category_id, locale, name, description)
select now(), now(), id, 'en', name, description from categories;

insert into product_translations (created_at, updated_at, product_id, locale, name, description)
select now(), now(), id, 'en', name, description from products;

-- Migrate the Portuguese category names introduced in V6.
insert into category_translations (created_at, updated_at, category_id, locale, name, description)
select now(), now(), id, 'pt', name_pt, null
from categories
where name_pt is not null;

alter table categories drop column if exists name_pt;
